-- =====================================================================
-- Offline completo: clientes de mostrador (sin cuenta) creados en el
-- dispositivo con id propio, retencion local configurable por tienda y
-- limpieza de la tabla de idempotencia.
-- Script idempotente. Docker init no lo reejecuta sobre un volumen existente.
-- =====================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS cliente_mostrador (
    id          UUID PRIMARY KEY,                       -- generated by the client, so it works offline
    tenant_id   UUID NOT NULL REFERENCES tienda(id) ON DELETE CASCADE,
    nombre      VARCHAR(80) NOT NULL,
    apellido    VARCHAR(80),
    celular     VARCHAR(20),
    ci          VARCHAR(20),
    correo      VARCHAR(120),
    creado_en   TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_cliente_mostrador_ci
    ON cliente_mostrador (tenant_id, ci) WHERE ci IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_cliente_mostrador_tenant_nombre
    ON cliente_mostrador (tenant_id, nombre);

ALTER TABLE cliente_mostrador ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON cliente_mostrador;
CREATE POLICY tenant_isolation ON cliente_mostrador
    USING (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid)
    WITH CHECK (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid);

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'aura_app') THEN
        GRANT SELECT, INSERT, UPDATE ON cliente_mostrador TO aura_app;
    END IF;
END $$;

ALTER TABLE nota_venta
    ADD COLUMN IF NOT EXISTS cliente_mostrador_id UUID REFERENCES cliente_mostrador(id) ON DELETE SET NULL;

-- How many days a device keeps its offline data (sales, customers, products) before purging it.
ALTER TABLE tienda ADD COLUMN IF NOT EXISTS retencion_offline_dias INTEGER NOT NULL DEFAULT 7;
ALTER TABLE tienda DROP CONSTRAINT IF EXISTS ck_tienda_retencion_offline_dias;
ALTER TABLE tienda ADD CONSTRAINT ck_tienda_retencion_offline_dias
    CHECK (retencion_offline_dias BETWEEN 1 AND 30);

-- Deletes idempotency keys older than `dias` days in every store. SECURITY DEFINER: it runs as its
-- owner (the table owner, exempt from RLS because no table uses FORCE ROW LEVEL SECURITY), so the
-- API role never needs BYPASSRLS and no policy is weakened. It touches nothing but idempotencia.
CREATE OR REPLACE FUNCTION idempotencia_purgar(dias integer) RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    borradas integer;
BEGIN
    IF dias IS NULL OR dias < 1 THEN
        RAISE EXCEPTION 'idempotencia_purgar: dias debe ser >= 1' USING ERRCODE = '22023';
    END IF;
    DELETE FROM idempotencia WHERE creado_en < now() - make_interval(days => dias);
    GET DIAGNOSTICS borradas = ROW_COUNT;
    RETURN borradas;
END;
$$;

REVOKE ALL ON FUNCTION idempotencia_purgar(integer) FROM PUBLIC;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'aura_app') THEN
        GRANT EXECUTE ON FUNCTION idempotencia_purgar(integer) TO aura_app;
    END IF;
END $$;

COMMIT;
